    private static var languageCode: String {
        effectiveLanguageCode
    }

    static var effectiveLanguageCode: String {
        let selected = UserDefaults.standard.string(forKey: "appLanguage")
            ?? AppLanguage.system.storageValue
        if selected == AppLanguage.system.storageValue {
            return Locale.current.language.languageCode?.identifier ?? "en"
        }
        return tables[selected] != nil ? selected : "en"
    }

    static func text(_ key: String) -> String {
        let lang = tables[languageCode] != nil ? languageCode : "en"
        return tables[lang]?[key] ?? tables["en"]?[key] ?? key
    }

    static func format(_ key: String, _ arguments: CVarArg...) -> String {
        String(format: text(key), locale: Locale.current, arguments: arguments)
    }
